#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn selector4x4_is_injective_and_covers_all_selectors() {
        let table = selector4x4();
        let mut seen = [false; 16];
        for row in table.iter() {
            assert!(row.a < 4 && row.b < 4);
            assert_eq!(row.selector as u32, row.a as u32 + 4 * row.b as u32);
            assert!(
                !seen[row.selector as usize],
                "duplicate selector {}",
                row.selector
            );
            seen[row.selector as usize] = true;
        }
        assert!(seen.iter().all(|&s| s), "missing selector value");
    }

    #[test]
    fn selector16_decode_is_total_and_consistent() {
        let table = selector16_decode();
        for (i, row) in table.iter().enumerate() {
            assert_eq!(row.selector as usize, i);
            assert!(row.base_index < 8);
            assert!(row.neg_bit < 2);
        }
        // Mirror symmetry: selector s and selector (15 - s) should pick the same
        // base index with opposite neg_bit (signs flip across the table midpoint).
        for s in 0..8u8 {
            assert_eq!(
                table[s as usize].base_index,
                table[(15 - s) as usize].base_index
            );
            assert_ne!(table[s as usize].neg_bit, table[(15 - s) as usize].neg_bit);
        }
    }

    #[test]
    fn final_selector_matches_spec_mapping() {
        let table = final_selector();
        assert_eq!(table[0].selector_final, 5);
        assert_eq!(table[0].init_base_index, 2);
        assert_eq!(table[1].selector_final, 6);
        assert_eq!(table[1].init_base_index, 3);
        assert_eq!(table[2].selector_final, 9);
        assert_eq!(table[2].init_base_index, 6);
        assert_eq!(table[3].selector_final, 10);
        assert_eq!(table[3].init_base_index, 7);
    }
}
